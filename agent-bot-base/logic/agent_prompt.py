    # описанию словами курьер часто не находит дом. Если в карточке лежит
    # текстовый адрес без ссылки — это видно модели, и она попросит дополнить.
    if address:
        has_map_link = "http" in address.lower()
        lines.append(
            f"— адрес доставки: {address}"
            + ("" if has_map_link else " (это текстом, без ссылки на Google Maps — попроси прислать ссылку)")
        )
    else:
        lines.append("— адрес доставки: НЕ ИЗВЕСТЕН, попроси ссылку из Google Maps")
    lines.append(f"— телефон: {phone}" if phone else "— телефон: НЕ ИЗВЕСТЕН")
    if restrictions:
        lines.append(f"— ограничения по еде из карточки: {', '.join(restrictions)}")
    else:
        lines.append("— ограничения по еде: в карточке не записаны, спроси и подтверди перед оформлением")
    if birthday_known:
        lines.append("— дата рождения: уже известна, НИКОГДА не спрашивай её снова (см. _BIRTHDAY_INSTRUCTION)")
    elif birthday_declined:
        lines.append(
            "— дата рождения: клиент ЯВНО отказался называть, НИКОГДА больше не спрашивай "
            "(см. _BIRTHDAY_INSTRUCTION)"
        )
    elif confirmed_orders_count is not None and confirmed_orders_count < 2:
        lines.append(
            "— дата рождения: ещё не известна, но сейчас СПРАШИВАТЬ РАНО — подтверждённых заказов клиента "
            f"пока {confirmed_orders_count}, вопрос уместен только начиная с 3-го заказа"
        )
    else:
        lines.append("— дата рождения: ещё не известна, можно аккуратно спросить один раз, если разговор располагает")
    # 06.08.2026 — активные подписки. Нужны, чтобы агент не оформлял вторую
    # молча: у клиента может быть несколько параллельных подписок (себе и
    # супруге), но это должен подтвердить он сам, а не решить модель.
    #
    # 18.08.2026 — РЕАЛЬНЫЙ БАГ, диалог dlg-78606415-3: разовый заказ
    # (paid_days=1) при апруве заводит строку в subscriptions со статусом
    # active точно так же, как обычная многодневная подписка — отдельного
    # признака "это был просто разовый заказ" нет. На следующий день клиент
    # попросил повторить точно такой же разовый заказ на новую дату; из-за
    # старой бинарной формулировки ("ещё один рацион для кого-то / продление")
    # модель не смогла отнести ответ клиента ("только для себя, только на
    # 1 день") ни к одному из двух вариантов и молча эскалировала голым
    # ESCALATE, не вызвав инструмент вовсе — клиент так и не был оформлен,
    # менеджер (Ольга) ответила ему в чате вручную, но заявку не завела.
    # Добавлен третий, ранее отсутствовавший случай — новый отдельный заказ
    # того же человека, не являющийся ни рационом для другого получателя, ни
    # продлением текущей подписки (см. формулировку ниже и в
