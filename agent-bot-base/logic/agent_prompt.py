    if not card:
        return ""
    lines = []
    address = (card.get("address_text") or "").strip()
    phone = (card.get("phone") or "").strip()
    restrictions = [r for r in (card.get("restrictions") or []) if r]
    birthday_known = bool(card.get("birthday_date"))
    birthday_declined = bool(card.get("birthday_declined"))
    confirmed_orders_count = card.get("confirmed_orders_count")
