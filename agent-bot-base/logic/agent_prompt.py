def strip_birthday_marker(text: str) -> tuple[str, str | None]:
    """Если ответ агента содержит строку 'BIRTHDAY: ДД.ММ' (см.
    _BIRTHDAY_INSTRUCTION; год — необязательный третий компонент, ДД.ММ.ГГГГ
    тоже распознаётся, но год отбрасывается) — вырезает её из текста
    (клиенту она попасть не должна) и возвращает дату в ISO-формате
    (YYYY-MM-DD, год — сентинел _BIRTHDAY_SENTINEL_YEAR) для записи в
    client_pii.birthday_date. Если маркера нет или день/месяц невалидны
    (несуществующие, например 31.02) — возвращает исходный текст без
    изменений и None, ничего не пишем в БД на всякий случай (лучше
    промолчать, чем записать мусор в карточку клиента)."""
    match = _BIRTHDAY_LINE_RE.search(text)
    if not match:
        return text, None
    cleaned = _BIRTHDAY_LINE_RE.sub("", text).rstrip()
    dd, mm = match.group(1).split(".")[:2]  # год, если модель его добавила, сознательно игнорируем
    try:
        date(_BIRTHDAY_SENTINEL_YEAR, int(mm), int(dd))
    except ValueError:
        return cleaned, None
    return cleaned, f"{_BIRTHDAY_SENTINEL_YEAR}-{mm}-{dd}"


