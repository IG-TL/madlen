"""
21.07.2026 — батчинг быстрых подряд сообщений одного клиента.

Запрос Игоря: "если клиент написал больше 1 сообщения подряд, тогда агент
должен учитывать это и разом ответить на все" — раньше каждое сообщение
клиента обрабатывалось независимо и немедленно: если человек писал "Привет"
и через секунду "у меня вопрос по цене" отдельным сообщением, агент отвечал
на каждое по отдельности, а не воспринимал их как один связный вопрос.

Механизм — счётчик поколений (generation) на клиента, БЕЗ отмены таймеров/
asyncio.Task: каждое новое сообщение добавляет текст в буфер клиента и
увеличивает generation. Отложенная проверка (см. main.py, вызывается после
паузы ожидания) передаёт generation, с которым она была запланирована —
если к моменту срабатывания generation клиента уже вырос (значит, пока эта
проверка ждала, клиент написал ещё), она ничего не делает — сработает более
новая проверка, запланированная позже. Работает корректно при любом числе
сообщений подряд, не требует отменять предыдущие отложенные задачи.

Реальное ожидание (asyncio.sleep) — в main.py, не здесь. Это НАМЕРЕННОЕ
разделение: секунды ожидания нельзя осмысленно проверить юнит-тестом без
реального сна (что делает тесты медленными и хрупкими), а вот саму логику
"что попадёт в батч, какая проверка выигрывает" — можно и нужно проверять
без единого sleep(). См. test_message_debounce.py.
"""

from __future__ import annotations

from typing import Optional

_pending_texts: dict[str, list[str]] = {}
_generation: dict[str, int] = {}


def enqueue(client_id: str, text: str) -> int:
    """Добавляет сообщение в буфер клиента, возвращает НОВОЕ поколение —
    его нужно передать в flush_if_current() при планировании отложенной
    проверки (после паузы ожидания)."""
    _pending_texts.setdefault(client_id, []).append(text)
    _generation[client_id] = _generation.get(client_id, 0) + 1
    return _generation[client_id]


def flush_if_current(client_id: str, generation: int) -> Optional[str]:
    """Вызывается ПОСЛЕ паузы ожидания с тем generation, что вернул enqueue()
    в момент планирования. Если за время паузы клиент написал ещё
    (generation клиента уже больше переданного) — возвращает None и НЕ
    трогает буфер (это должна сделать более новая проверка). Иначе — забирает
    все накопленные с последнего сброса сообщения, склеивает через перенос
    строки в один текст, очищает буфер клиента и возвращает текст."""
    if _generation.get(client_id) != generation:
        return None
    texts = _pending_texts.pop(client_id, [])
    _generation.pop(client_id, None)
    if not texts:
        return None
    return "\n".join(texts)


def pending_count(client_id: str) -> int:
    """Для отладки/тестов — сколько сообщений сейчас в буфере клиента."""
    return len(_pending_texts.get(client_id, []))
